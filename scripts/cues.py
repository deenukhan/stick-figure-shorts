"""Turn a word-timed transcript into the film's cue data: words.ts (karaoke words + caption chunks) and a printed cue table.

usage: python3 cues.py <transcript.json> <out/words.ts> [--lead 15] [--fps 30] [--max 4]
transcript.json is what the studio's transcribe.py writes: [{s, e, t, words:[{w, s, e}]}].
Film frame of a word = lead + round(seconds * fps). The narration is muxed at +lead frames, so these frames match the picture.
"""
import argparse, json, re

ap = argparse.ArgumentParser()
ap.add_argument("src")
ap.add_argument("out")
ap.add_argument("--lead", type=int, default=15)
ap.add_argument("--fps", type=int, default=30)
ap.add_argument("--max", type=int, default=4, help="max words per caption chunk")
a = ap.parse_args()

raw = [w for seg in json.load(open(a.src)) for w in seg["words"]]
words = []
for w in raw:
    t = w["w"].strip()
    # whisper splits "17,000" into "17" + ",000" and "50-50" into "50" + "-50": glue the tails back on
    if words and (re.match(r"^[,.]\d", t) or t.startswith("-")):
        words[-1]["w"] += t; words[-1]["e"] = w["e"]; continue
    words.append({"w": t, "s": w["s"], "e": w["e"]})

F = lambda sec: a.lead + round(sec * a.fps)
W = [(F(w["s"]), F(w["e"]), w["w"]) for w in words]

# caption chunks: break after punctuation, after --max words, or at a pause > 0.35 s
chunks, cur = [], []
for i, w in enumerate(words):
    cur.append(i)
    nxt = words[i + 1] if i + 1 < len(words) else None
    if re.search(r"[.,?!;:]$", w["w"]) or len(cur) >= a.max or not nxt or nxt["s"] - w["e"] > 0.35:
        chunks.append((cur[0], cur[-1])); cur = []

with open(a.out, "w") as f:
    f.write("// Generated by stick-figure-shorts/scripts/cues.py from " + a.src.split("/")[-1] + f" (lead {a.lead} frames, {a.fps} fps).\n")
    f.write("// WORDS: [startFrame, endFrame, word]. CHUNKS: [firstWord, lastWord] shown together as one caption.\n")
    f.write("export const WORDS: [number, number, string][] = [\n")
    for s, e, t in W:
        f.write(f"  [{s}, {e}, {json.dumps(t)}],\n")
    f.write("];\nexport const CHUNKS: [number, number][] = [\n")
    for c in chunks:
        f.write(f"  [{c[0]}, {c[1]}],\n")
    f.write(f"];\nexport const VOICE_END = {W[-1][1]};\n")

print(f"{'frame':>6} {'end':>5}  word")
for s, e, t in W:
    print(f"{s:6d} {e:5d}  {t}")
print(f"-> {a.out}: {len(W)} words, {len(chunks)} caption chunks, voice ends at frame {W[-1][1]}")
